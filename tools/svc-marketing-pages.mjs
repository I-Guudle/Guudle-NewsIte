function relatedFor(slug) {
  const idx = MARKETING_SLUGS.indexOf(slug);
  const picks = [1, 2, 3, 5].map((o) => MARKETING_SLUGS[(idx + o) % MARKETING_SLUGS.length]);
  return [...new Set(picks.filter((s) => s !== slug))].slice(0, 4).map((s) => ({
    href: `${s}.html`,
    label: SLUG_LABELS[s] || s,
  }));
}

